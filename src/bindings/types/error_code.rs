use crate::bindings::tarantool::tarantool::types::ErrorCode;

macro_rules! error_codes {
    ($($variant:ident),+ $(,)?) => {
        impl From<ErrorCode> for u32 {
            fn from(code: ErrorCode) -> Self {
                match code {
                    $(ErrorCode::$variant => ErrorCode::$variant as u16 as u32,)+
                }
            }
        }

        impl core::convert::TryFrom<u32> for ErrorCode {
            type Error = ();

            fn try_from(value: u32) -> Result<Self, Self::Error> {
                match value {
                    $(value if value == ErrorCode::$variant as u16 as u32 => Ok(ErrorCode::$variant),)+
                    _ => Err(()),
                }
            }
        }
    };
}

